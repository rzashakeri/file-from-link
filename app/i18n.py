def t(lang: str, key: str, **kw) -> str:
    s = STRINGS.get(lang, STRINGS[DEFAULT_LANG]).get(key) or STRINGS[DEFAULT_LANG][key]
    return s.format(**kw) if kw else s
def fmt_label(lang: str, choice: str) -> str:
    return t(lang, f"fmt_{choice}")
